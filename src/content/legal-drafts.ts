let keyCounter = 0;
const key = () => `k${(keyCounter++).toString(36)}`;

export interface PortableBlock {
  _type: 'block';
  _key: string;
  style: 'normal' | 'h2';
  markDefs: [];
  children: { _type: 'span'; _key: string; text: string; marks: [] }[];
}

export function draftToPortableText(draft: LegalDraft): PortableBlock[] {
  const blocks: PortableBlock[] = [];
  for (const section of draft.sections) {
    blocks.push({
      _type: 'block',
      _key: key(),
      style: 'h2',
      markDefs: [],
      children: [{ _type: 'span', _key: key(), text: section.heading, marks: [] }],
    });
    for (const p of section.paragraphs) {
      blocks.push({
        _type: 'block',
        _key: key(),
        style: 'normal',
        markDefs: [],
        children: [{ _type: 'span', _key: key(), text: p, marks: [] }],
      });
    }
  }
  return blocks;
}
